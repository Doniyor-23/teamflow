import { Router } from 'express';
import { auth, role, wrap as w } from './middleware.js';
import * as c from './controllers.js'; import * as n from './notifications.js'; import * as a from './admin.js'; import * as ch from './chat.js'; import { listActivity } from './activity.js';
const r = Router();
r.post('/auth/register', w(c.register)); r.post('/auth/login', w(c.login)); r.post('/auth/verify', w(c.verifyEmail)); r.post('/auth/resend', w(c.resend));
r.post('/auth/forgot', w(c.forgot)); r.post('/auth/reset', w(c.reset)); r.get('/auth/me', auth, c.me);
r.use(auth);
r.get('/users', w(c.listUsers)); r.get('/dashboard', w(c.dashboard));
r.route('/projects').get(w(c.listProjects)).post(w(c.createProject));
r.route('/projects/:id').put(w(c.updateProject)).delete(w(c.deleteProject));
r.route('/tasks').get(w(c.listTasks)).post(w(c.createTask));
r.patch('/tasks/reorder', w(c.reorderTasks));
r.route('/tasks/:id').put(w(c.updateTask)).delete(w(c.deleteTask));
r.get('/notifications', w(n.listNotifications)); r.patch('/notifications/read-all', w(n.readAll)); r.patch('/notifications/:id/read', w(n.readNotification));
r.get('/chat/conversations', w(ch.list)); r.post('/chat/direct', w(ch.direct)); r.post('/chat/groups', role('admin', 'manager'), w(ch.createGroup)); r.put('/chat/groups/:id', w(ch.updateGroup));
r.route('/chat/messages/:id').put(w(ch.edit)).delete(w(ch.remove));
r.get('/chat/:id/messages', w(ch.messages)); r.post('/chat/:id/messages', w(ch.send)); r.post('/chat/:id/read', w(ch.read));
r.get('/activity', role('admin', 'manager'), w(listActivity));
r.get('/admin/users', role('admin'), w(a.users)); r.patch('/admin/users/:id', role('admin'), w(a.updateUser)); r.post('/admin/users/invite', role('admin'), w(a.invite)); r.get('/admin/stats', role('admin'), w(a.stats));
export default r;
